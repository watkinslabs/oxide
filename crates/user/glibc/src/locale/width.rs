// Sorted, non-overlapping [lo,hi] ranges of East-Asian wide/fullwidth chars.
const WIDE: &[(u32, u32)] = &[
    (0x1100, 0x115F), (0x2329, 0x232A), (0x2E80, 0x303E), (0x3041, 0x33FF),
    (0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xA000, 0xA4CF), (0xAC00, 0xD7A3),
    (0xF900, 0xFAFF), (0xFE10, 0xFE19), (0xFE30, 0xFE6F), (0xFF00, 0xFF60),
    (0xFFE0, 0xFFE6), (0x20000, 0x3FFFD),
];

fn in_ranges(c: u32, t: &[(u32, u32)]) -> bool {
    let (mut lo, mut hi) = (0usize, t.len());
    while lo < hi {
        let m = (lo + hi) / 2;
        if c < t[m].0 { hi = m; } else if c > t[m].1 { lo = m + 1; } else { return true; }
    }
    false
}

/// # C: internal — column width of one Unicode scalar (wcwidth core).
pub(crate) fn width_of(c: u32) -> i32 {
    if c == 0 { return 0; }
    if c < 0x20 || (0x7f..0xa0).contains(&c) { return -1; } // C0/C1 controls
    if in_ranges(c, ZERO) { return 0; }
    if in_ranges(c, WIDE) { 2 } else { 1 }
}

// # C: int wcwidth(wchar_t wc)
#[no_mangle]
pub extern "C" fn wcwidth(wc: i32) -> i32 { width_of(wc as u32) }

// # C: int wcswidth(const wchar_t *s, size_t n)
#[no_mangle]
pub unsafe extern "C" fn wcswidth(s: *const i32, n: usize) -> i32 {
    // SAFETY: s is a wchar_t array of at least n elements (or NUL-terminated
    // within n); we sum each column width, returning -1 at the first
    // non-printable per the C contract.
    unsafe {
        let mut total = 0;
        let mut i = 0;
        while i < n {
            let wc = *s.add(i);
            if wc == 0 { break; }
            let w = width_of(wc as u32);
            if w < 0 { return -1; }
            total += w;
            i += 1;
        }
        total
    }
}
