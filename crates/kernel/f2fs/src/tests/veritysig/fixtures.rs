/// Decode a hex string. # C: O(n)
pub fn unhex(s: &str) -> alloc::vec::Vec<u8> {
    let b = s.as_bytes();
    (0..b.len() / 2).map(|i| nyb(b[i * 2]) << 4 | nyb(b[i * 2 + 1])).collect()
}
fn nyb(c: u8) -> u8 { if c.is_ascii_digit() { c - b'0' } else { c - b'a' + 10 } }
