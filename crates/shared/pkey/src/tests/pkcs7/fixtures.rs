/// Decode a hex string. # C: O(n)
pub fn unhex(s: &str) -> alloc::vec::Vec<u8> {
    let b = s.as_bytes();
    (0..b.len() / 2).map(|i| nyb(b[i * 2]) << 4 | nyb(b[i * 2 + 1])).collect()
}
fn nyb(c: u8) -> u8 { if c.is_ascii_digit() { c - b'0' } else { c - b'a' + 10 } }

/// A store holding just the signing certificate.
pub fn leaf_store() -> crate::pkcs7::TrustStore {
    let mut s = crate::pkcs7::TrustStore::new();
    s.add(&unhex(LEAF_DER)).expect("the leaf certificate parses");
    s
}

/// A store holding just the authority that issued it.
pub fn ca_store() -> crate::pkcs7::TrustStore {
    let mut s = crate::pkcs7::TrustStore::new();
    s.add(&unhex(CA_DER)).expect("the authority certificate parses");
    s
}

