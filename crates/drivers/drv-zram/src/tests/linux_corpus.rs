fn linux_fixture_page() -> [u8; LINUX_FIXTURE_BYTES] {
    let mut page = [0; LINUX_FIXTURE_BYTES];
    for (index, byte) in page.iter_mut().enumerate() {
        *byte = ((index * LINUX_PATTERN_FACTOR) % LINUX_PATTERN_MODULUS) as u8;
    }
    page[LINUX_ZERO_OFFSET..LINUX_ZERO_OFFSET + LINUX_ZERO_BYTES].fill(0);
    page
}

#[test]
fn linux_lzorle_stream_decodes_and_oxide_stream_is_consumable() {
    let expected = linux_fixture_page();
    let mut decoded = [0; LINUX_FIXTURE_BYTES];
    lzorle::decompress(LINUX_LZORLE_STREAM, &mut decoded).unwrap();
    assert_eq!(decoded, expected);
    let streams = lzo::Streams::new();
    let oxide_stream = lzorle::compress(&expected, &streams).unwrap();
    lzorle::decompress(&oxide_stream, &mut decoded).unwrap();
    assert_eq!(decoded, expected);
}

#[test]
fn linux_lz4hc_stream_decodes_and_oxide_stream_is_independently_consumable() {
    let expected = linux_fixture_page();
    let mut decoded = [0; LINUX_FIXTURE_BYTES];
    assert_eq!(lz4_flex::block::decompress_into(LINUX_LZ4HC_STREAM, &mut decoded).unwrap(), LINUX_FIXTURE_BYTES);
    assert_eq!(decoded, expected);
    let oxide_stream = lz4hc::compress(&expected, &[], crate::deflate::PARAM_NOT_SET);
    assert_eq!(lz4_flex::block::decompress_into(&oxide_stream, &mut decoded).unwrap(), LINUX_FIXTURE_BYTES);
    assert_eq!(decoded, expected);
}

#[test]
fn linux_842_stream_decodes_and_oxide_stream_preserves_the_linux_frame_contract() {
    let expected = linux_fixture_page();
    let mut decoded = [0; LINUX_FIXTURE_BYTES];
    eight42::decompress(LINUX_842_STREAM, &mut decoded).unwrap();
    assert_eq!(decoded, expected);
    let oxide_stream = eight42::compress(&expected).unwrap();
    eight42::decompress(&oxide_stream, &mut decoded).unwrap();
    assert_eq!(decoded, expected);
}
